#!/usr/bin/env node
// Design tokens for the game: builds tokens/*.json (Quantum Design, Global → System → Component) with
// scripts/quantum-tokens.mjs, then keeps only what the game uses, so the page carries a few hundred bytes of
// variables instead of the whole kit (~77 KB).
//
//   node scripts/tokens.mjs           writes src/styles/design-tokens.css
//   node scripts/tokens.mjs --check   fails when that file is out of date (CI)
//
// Kept: every component token named in index.html or src/, plus the system and global tokens they resolve
// through. The dark theme follows the game's own switch: data-theme="dark" on <html>, or the system's dark
// mode unless data-theme="light".

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const OUT = path.join(root, 'src/styles/design-tokens.css');
const USERS = [path.join(root, 'index.html'), path.join(root, 'src')];
const USAGE = /--components-tokens--[a-z0-9-]+/g;
const REF = /var\((--[a-z0-9-]+)\)/g;

const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'tokens-')), 'all.css');
execFileSync(process.execPath, [path.join(root, 'scripts/quantum-tokens.mjs'), 'build', '--src', path.join(root, 'tokens'), '--out', tmp], { stdio: 'pipe' });
const full = fs.readFileSync(tmp, 'utf8');

/** Each block of the generated file: its selector and its declarations, in order. */
const blocks = [...full.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(([, selector, body]) => ({
  selector: selector.replace(/\/\*[\s\S]*?\*\//g, '').trim(),
  decls: [...body.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => ({ name, value: value.trim() })),
}));

function filesUnder(p) {
  if (fs.statSync(p).isFile()) return [p];
  return fs.readdirSync(p, { withFileTypes: true }).flatMap((e) => (e.name === 'styles' && p.endsWith('src') ? [] : filesUnder(path.join(p, e.name))));
}

const used = new Set();
for (const file of USERS.flatMap(filesUnder)) for (const m of fs.readFileSync(file, 'utf8').matchAll(USAGE)) used.add(m[0]);

// Everything those tokens reach, in any theme.
const keep = new Set(used);
for (let grew = true; grew; ) {
  grew = false;
  for (const b of blocks) for (const d of b.decls) {
    if (!keep.has(d.name)) continue;
    for (const [, ref] of d.value.matchAll(REF)) if (!keep.has(ref)) keep.add(ref), (grew = true);
  }
}
const missing = [...used].filter((name) => !blocks.some((b) => b.decls.some((d) => d.name === name)));
if (missing.length) {
  console.error(`✖ Not in tokens/components.json: ${missing.join(', ')}`);
  process.exit(1);
}

// Fixed roles (the grimoire's paper and ink) are the same in both themes: the dark blocks only carry what changes.
const light = new Map(blocks.find((b) => b.selector.includes('[data-theme="light"]'))?.decls.map((d) => [d.name, d.value]) ?? []);
const isDark = (b) => b.selector === '[data-theme="dark"]';
const kept = (b) =>
  b.decls
    .filter((d) => keep.has(d.name) && !(isDark(b) && light.get(d.name) === d.value))
    .map((d) => `  ${d.name}: ${d.value};`)
    .join('\n');
const out = [];
for (const b of blocks) {
  const body = kept(b);
  if (!body) continue;
  if (isDark(b)) {
    out.push(`@media (prefers-color-scheme: dark) {\n:root:not([data-theme="light"]) {\n${body}\n}\n}`);
    out.push(`:root[data-theme="dark"] {\n${body}\n}`);
  } else out.push(`${b.selector} {\n${body}\n}`);
}
const css =
  `/* GENERATED by scripts/tokens.mjs from tokens/*.json — do not edit; run npm run tokens. ${used.size} component tokens. */\n` +
  out.join('\n') +
  '\n';

if (process.argv.includes('--check')) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (now !== css) {
    console.error('✖ src/styles/design-tokens.css is out of date: run npm run tokens');
    process.exit(1);
  }
  console.log(`✔ design tokens up to date (${used.size} component tokens, ${css.length} bytes)`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, css);
  console.log(`✔ ${path.relative(root, OUT)}: ${used.size} component tokens, ${keep.size} variables, ${css.length} bytes`);
}
